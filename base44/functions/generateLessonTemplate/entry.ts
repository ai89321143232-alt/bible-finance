const COL_WIDTHS = [
  { wch: 30 }, // module_title
  { wch: 45 }, // module_description
  { wch: 30 }, // lesson_title
  { wch: 70 }, // lesson_content
  { wch: 60 }, // assignment
  { wch: 20 }, // lesson_attachment
  { wch: 20 }, // assignment_attachment
  { wch: 20 }, // module_poster
];

export default async function () {
  const ws = XLSX.utils.json_to_sheet(SAMPLE_ROWS);
  ws['!cols'] = COL_WIDTHS;
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Уроки');
  const buf = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' });
  return new Response(buf, {
    headers: {
      'Content-Type': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
      'Content-Disposition': 'attachment; filename="lesson_template.xlsx"',
    },
  });
}